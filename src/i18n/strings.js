export const STRINGS = Object.freeze({ zh: Object.freeze(zh), en: Object.freeze(en) });

/** Look up a string, fill {placeholders}, fall back to English and then to the key itself. */
export function translate(lang, key, params = {}) {
  const raw = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

/** 'zh' or 'en' from the stored preference, or from the browser's languages when it is 'auto'. */
export function resolveLang(pref, browserLanguages) {
  if (pref === 'zh' || pref === 'en') return pref;
  const first = (browserLanguages ?? []).find((l) => typeof l === 'string');
  return first && first.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
